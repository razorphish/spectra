#!/usr/bin/env node
/**
 * Overwrites apps/admin-ui/src/environments/environment.generated.ts (tracked stub) for CI/staff deploys.
 *
 * Env (typical CI):
 * - STAFF_API_URL — absolute base URL of admin-ui-api (e.g. https://admin-api.example.com)
 * - STAFF_AUTH0_ENABLED — optional, "true" to turn on Auth0 in the generated bundle
 * - STAFF_AUTH0_DOMAIN, STAFF_AUTH0_CLIENT_ID, STAFF_AUTH0_AUDIENCE — optional Auth0 SPA + API identifier
 * - STAFF_AUTH0_REDIRECT_URI — optional full OAuth callback URL (otherwise `{origin}/auth/callback` in the browser)
 * - STAFF_AUTH0_LOGOUT_RETURN_TO — optional post-logout URL (must be in Auth0 Allowed Logout URLs)
 *
 * Build with: npx nx build admin-ui --configuration=ci-staff
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outPath = join(root, 'apps/admin-ui/src/environments/environment.generated.ts');

const staff = process.env['STAFF_API_URL'] ?? '';
const domain = process.env['STAFF_AUTH0_DOMAIN'] ?? '';
const clientId = process.env['STAFF_AUTH0_CLIENT_ID'] ?? '';
const audience = process.env['STAFF_AUTH0_AUDIENCE'] ?? '';
const redirectUri = process.env['STAFF_AUTH0_REDIRECT_URI']?.trim() ?? '';
const logoutReturnTo = process.env['STAFF_AUTH0_LOGOUT_RETURN_TO']?.trim() ?? '';
const enabled =
  String(process.env['STAFF_AUTH0_ENABLED'] ?? '').toLowerCase() === 'true';
const auth0Enabled = !!(enabled && domain && clientId);

const content = `/* Generated by scripts/write-admin-ui-build-environment.mjs — do not edit by hand */
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(staff)},
  appTarget: 'admin' as const,
  auth0: {
    requested: ${enabled},
    enabled: ${auth0Enabled},
    domain: ${JSON.stringify(domain)},
    clientId: ${JSON.stringify(clientId)},
    audience: ${JSON.stringify(audience)},
    redirectUri: ${JSON.stringify(redirectUri)},
    logoutReturnTo: ${JSON.stringify(logoutReturnTo)},
  },
  telemetry: {
    enabled: false,
    dsn: undefined as string | undefined,
  },
};
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[write-admin-ui-build-environment] wrote ${outPath}`);
