#!/usr/bin/env node
/**
 * Generates apps/admin-ui/src/environments/environment.auth0.local.ts from env files.
 *
 * Load order (later overrides earlier for overlapping keys):
 * 1. Workspace root `.env` — only variables prefixed with `ADMIN_UI_`
 * 2. `apps/admin-ui/.env`
 * 3. `apps/admin-ui/.env.local` (optional overrides)
 *
 * **Nx:** `admin-ui:env-sync` must stay **uncached** (`project.json` cache: false). Env files are
 * usually gitignored; cached env-sync can keep serving an old `environment.auth0.local.ts` even
 * after you fix `ADMIN_UI_AUTH0_*` in `.env`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'dotenv';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const adminRoot = join(root, 'apps/admin-ui');
const outPath = join(adminRoot, 'src/environments/environment.auth0.local.ts');

const PREFIX = 'ADMIN_UI_';

function loadEnvFile(path) {
  if (!existsSync(path)) return {};
  try {
    return parse(readFileSync(path, 'utf8'));
  } catch {
    return {};
  }
}

function truthy(raw) {
  if (raw == null || raw === '') return false;
  const s = String(raw).trim().toLowerCase();
  return s === '1' || s === 'true' || s === 'yes' || s === 'on';
}

function pick(env, key, fallback = '') {
  const v = env[key];
  if (v == null) return fallback;
  return String(v).trim();
}

/** Merge only ADMIN_UI_* from a full env object. */
function adminUiPrefixed(env) {
  const out = {};
  for (const [k, v] of Object.entries(env)) {
    if (k.startsWith(PREFIX) && typeof v === 'string' && v.length > 0) {
      out[k] = v.trim();
    }
  }
  return out;
}

const merged = {};

const rootParsed = loadEnvFile(join(root, '.env'));
Object.assign(merged, adminUiPrefixed(rootParsed));

const appParsed = loadEnvFile(join(adminRoot, '.env'));
Object.assign(merged, appParsed);

const appLocalParsed = loadEnvFile(join(adminRoot, '.env.local'));
Object.assign(merged, appLocalParsed);

const apiBaseUrl =
  pick(merged, 'ADMIN_UI_API_BASE_URL') || 'http://127.0.0.1:3002';
const enabled = truthy(merged['ADMIN_UI_AUTH0_ENABLED']);
const domain = pick(merged, 'ADMIN_UI_AUTH0_DOMAIN');
const clientId = pick(merged, 'ADMIN_UI_AUTH0_CLIENT_ID');
const audience = pick(merged, 'ADMIN_UI_AUTH0_AUDIENCE');
const redirectUriOverride = pick(merged, 'ADMIN_UI_AUTH0_REDIRECT_URI');
const logoutReturnToOverride = pick(merged, 'ADMIN_UI_AUTH0_LOGOUT_RETURN_TO');
const auth0On = !!(enabled && domain && clientId);

const aviateSwaggerDocsUrl =
  pick(merged, 'ADMIN_UI_AVIATE_SWAGGER_URL') ||
  'http://127.0.0.1:3001/integration/docs/';

const content = `/* eslint-disable */
/* Auto-generated by scripts/sync-admin-ui-env.mjs — do not edit */

export const apiBaseUrlFromDotEnv = ${JSON.stringify(apiBaseUrl)};

export const aviateSwaggerDocsUrlFromDotEnv = ${JSON.stringify(aviateSwaggerDocsUrl)};

export const redirectUriFromDotEnv = ${JSON.stringify(redirectUriOverride)};

export const auth0FromDotEnv = {
  /** \`ADMIN_UI_AUTH0_ENABLED\` — intent to use Auth0 (even if client id is still empty). */
  requested: ${JSON.stringify(enabled)},
  /** Runtime: requested + non-empty domain + client id (\`provideAuth0\` on). */
  enabled: ${JSON.stringify(auth0On)},
  domain: ${JSON.stringify(domain)},
  clientId: ${JSON.stringify(clientId)},
  audience: ${JSON.stringify(audience)},
  /** \`ADMIN_UI_AUTH0_LOGOUT_RETURN_TO\` — must match Auth0 Allowed Logout URLs exactly when set. */
  logoutReturnTo: ${JSON.stringify(logoutReturnToOverride)},
} as const;
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[sync-admin-ui-env] wrote ${outPath}`);
console.log(
  `[sync-admin-ui-env] ADMIN_UI_AUTH0_AUDIENCE -> ${audience || '(empty)'}`,
);
