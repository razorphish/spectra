#!/usr/bin/env node
/**
 * Generates apps/sandbox-ui/src/environments/environment.auth0.local.ts from env files.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'dotenv';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const sandboxRoot = join(root, 'apps/sandbox-ui');
const outPath = join(sandboxRoot, 'src/environments/environment.auth0.local.ts');

const PREFIX = 'SANDBOX_UI_';

function loadEnvFile(path) {
  if (!existsSync(path)) return {};
  try {
    return parse(readFileSync(path, 'utf8'));
  } catch {
    return {};
  }
}

function truthy(raw) {
  if (raw == null || raw === '') return false;
  const s = String(raw).trim().toLowerCase();
  return s === '1' || s === 'true' || s === 'yes' || s === 'on';
}

function pick(env, key, fallback = '') {
  const v = env[key];
  if (v == null) return fallback;
  return String(v).trim();
}

function sandboxPrefixed(env) {
  const out = {};
  for (const [k, v] of Object.entries(env)) {
    if (k.startsWith(PREFIX) && typeof v === 'string' && v.length > 0) {
      out[k] = v.trim();
    }
  }
  return out;
}

const merged = {};
Object.assign(merged, sandboxPrefixed(loadEnvFile(join(root, '.env'))));
Object.assign(merged, loadEnvFile(join(sandboxRoot, '.env')));
Object.assign(merged, loadEnvFile(join(sandboxRoot, '.env.local')));

const apiBaseUrl =
  pick(merged, 'SANDBOX_UI_API_BASE_URL') || 'http://127.0.0.1:3000';
/** When set, Swagger “API reference” uses this origin; otherwise same as API base (public `/docs` only). */
const publicApiDocsBaseUrl =
  pick(merged, 'SANDBOX_UI_PUBLIC_API_DOCS_BASE_URL') || apiBaseUrl;
const enabled = truthy(merged['SANDBOX_UI_AUTH0_ENABLED']);
const domain = pick(merged, 'SANDBOX_UI_AUTH0_DOMAIN');
const clientId = pick(merged, 'SANDBOX_UI_AUTH0_CLIENT_ID');
const audience = pick(merged, 'SANDBOX_UI_AUTH0_AUDIENCE');
const auth0On = !!(enabled && domain && clientId);

const content = `/* eslint-disable */
/* Auto-generated by scripts/sync-sandbox-ui-env.mjs — do not edit */

export const apiBaseUrlFromDotEnv = ${JSON.stringify(apiBaseUrl)};

export const publicApiDocsBaseUrlFromDotEnv = ${JSON.stringify(publicApiDocsBaseUrl)};

export const auth0FromDotEnv = {
  requested: ${JSON.stringify(enabled)},
  enabled: ${JSON.stringify(auth0On)},
  domain: ${JSON.stringify(domain)},
  clientId: ${JSON.stringify(clientId)},
  audience: ${JSON.stringify(audience)},
} as const;
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[sync-sandbox-ui-env] wrote ${outPath}`);
